ok('login admin', (await A('POST', '/api/login', { email: 'test-admin@example.invalid', password: 'contraseña-de-prueba-1' })).s === 200);
await M('POST', '/api/login', { email: 'test-member@example.invalid', password: 'contraseña-de-prueba-1' });
